ROOT = os.path.abspath(os.path.join(SW, '..'))
sys.path.insert(0, SW)
import chainflat_graph as cg                                   # noqa: E402

SCRATCH = os.path.expanduser('~/.cache/ucsimt-tmp/chainflat')
UC = os.path.join(ROOT, 'hdl/rtl/ucore')
TB = os.path.join(ROOT, 'hdl/tb')

# THE LOOP, VERBATIM.  If this anchor ever fails to match, the generator
# REFUSES rather than guessing -- a silent miss would leave the flat tree
# identical to the reference and the comparison would read "no difference".
LOOP_ANCHOR = """        for (chain = 0; chain < CHAIN_MAX; chain = chain + 4'd1) begin
            if (!stop) begin"""
LOOP_END = """                if ((chain != 4'd0) && !st_zero_ok(st_n)) stop = 1'b1;
                else begin
                    `include "v30u_eu_step.svh"
                end
            end
        end"""


def topo_order(adj, states):
    """A topological order of the chainable states under the fall-through
    edges.  Refuses if the sub-graph is not a DAG."""
    edges = {s: {t for t, _ in adj.get(s, []) if t in states} for s in states}
    order, seen, mark = [], set(), set()

    def visit(n):
        if n in seen:
            return
        if n in mark:
            raise RuntimeError('the fall-through sub-graph has a CYCLE at ' + n)
        mark.add(n)
        for t in sorted(edges[n]):
            visit(t)
        mark.discard(n)
        seen.add(n)
        order.append(n)
    for s in sorted(states):
        visit(s)
    return list(reversed(order))


def split_arms(uc, outdir, states):
    """Write one `cf_arm_<S>.svh` per chainable state, carved out of
    `v30u_eu_step.svh` VERBATIM (comments and all -- the body is not rewritten,
    only relocated)."""
    txt = open(os.path.join(uc, 'v30u_eu_step.svh')).read()
    lines = txt.split('\n')
    starts = []
    for i, l in enumerate(lines):
        m = re.match(r'^(S_[A-Z0-9_]+|default):', l)
        if m:
            starts.append((i, m.group(1), m.end()))
    starts.append((len(lines), None, 0))
    made = {}
    for k in range(len(starts) - 1):
        i, name, off = starts[k]
        if name not in states:
            continue
        j = starts[k + 1][0]
        body = [lines[i][off:]] + lines[i + 1:j]
        # the LAST arm carries the file's trailing `endcase`
        body = re.sub(r'\bendcase\s*$', '', '\n'.join(body).rstrip())
        fn = f'cf_arm_{name}.svh'
        open(os.path.join(outdir, fn), 'w').write(
            f'// WAVE 6 PROTOTYPE -- {name}, carved VERBATIM out of\n'
            f'// v30u_eu_step.svh.  Generated by sw/chainflat_proto.py.\n'
            + body + '\n')
        made[name] = fn
    missing = states - set(made)
    if missing:
        raise RuntimeError('arms not found in the step file: %s' % missing)
    return made


def make_flat(uc, outdir):
    g = cg.graph(uc)
    states = set(g['st_zero_ok'])
    order = topo_order(g['adj'], states)
    made = split_arms(uc, outdir, states)
    eu = os.path.join(outdir, 'v30u_eu.sv')
    txt = open(eu).read()
    a = txt.find(LOOP_ANCHOR)
    b = txt.find(LOOP_END)
    if a < 0 or b < 0 or b < a:
        raise RuntimeError('REFUSING: the chain-loop anchor did not match '
                           'verbatim (a=%d b=%d)' % (a, b))
    b += len(LOOP_END)
    new = ['        //================================================='
           '=================',
           '        // WAVE 6 PROTOTYPE -- THE FLATTENED CHAIN.  GENERATED; '
           'NOT A DESIGN.',
           '        // position 0 is the 33-arm case once; then the nine '
           'chainable arms,',
           '        // ONCE EACH, in topological order.  See '
           'sw/chainflat_proto.py.',
           '        //================================================='
           '=================',
           "        chain = 4'd0;",
           '`ifndef SYNTHESIS',
           "        chain_used = 4'd1;",
           '`endif',
           '        `include "v30u_eu_step.svh"',
           "        chain = 4'd1;",
           '        // the loop\'s own fail-safe, applied once: a position-0 '
           'arm that',
           '        // falls through to a state no block below covers ends the '
           'edge here.',
           '        if (!stop && !st_zero_ok(st_n)) stop = 1\'b1;']
    for s in order:
        new += [f'        if (!stop && (st_n == {s})) begin',
                '`ifndef SYNTHESIS',
                "            chain_used = chain_used + 4'd1;",
                '`endif',
                f'            `include "{made[s]}"',
                '        end']
    open(eu, 'w').write(txt[:a] + '\n'.join(new) + txt[b:])
    return {'topological_order': order, 'arms': made}


def gen(force=False):
    os.makedirs(SCRATCH, exist_ok=True)
    out = {}
    for kind in ('ref', 'flat'):
        d = os.path.join(SCRATCH, 'tree_' + kind)
        if os.path.exists(d):
            shutil.rmtree(d)
        shutil.copytree(UC, d)
        out[kind] = d
    meta = make_flat(UC, out['flat'])
    # the reference must be BYTE-IDENTICAL to the tree
    r = subprocess.run(['diff', '-r', UC, out['ref']], capture_output=True,
                       text=True)
    meta['ref_identical'] = (r.returncode == 0)
    meta['flat_diff_lines'] = len(subprocess.run(
        ['diff', '-u', os.path.join(UC, 'v30u_eu.sv'),
         os.path.join(out['flat'], 'v30u_eu.sv')],
        capture_output=True, text=True).stdout.split('\n'))
    meta['trees'] = out
    print('REF  %s   byte-identical to hdl/rtl/ucore: %s'
          % (out['ref'], meta['ref_identical']))
    print('FLAT %s   topological order: %s'
          % (out['flat'], ' -> '.join(meta['topological_order'])))
    return meta


