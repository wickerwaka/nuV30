PORT_RE = re.compile(r'^\s*(input|output|inout)\s+(?:wire\s+|reg\s+|logic\s+)?'
                     r'(?:\[[^\]]*\]\s*)?([A-Za-z_][A-Za-z0-9_]*)')


def ports(tree):
    txt = open(os.path.join(tree, 'v30u_eu.sv')).read()
    m = re.search(r'^module\s+v30u_eu\s*\((.*?)^\);', txt, re.S | re.M)
    out = []
    for line in m.group(1).split('\n'):
        line = line.split('//')[0]
        mm = PORT_RE.match(line)
        if mm:
            out.append(mm.group(2))
    return out


QSF = """# WAVE 6 -- STANDALONE `v30u_eu` PROJECT.  GENERATED by sw/chainflat_proto.py.
# It is NOT the design; it is the sec.51.1 harness (`v30u_eu` as its own top
# with virtual pins), used here so the two chain forms are compiled ALONE and
# compared to each other.  NO Fmax quoted from it is a design figure.
set_global_assignment -name FAMILY "Cyclone V"
set_global_assignment -name DEVICE 5CSEBA6U23I7
set_global_assignment -name TOP_LEVEL_ENTITY v30u_eu
set_global_assignment -name LAST_QUARTUS_VERSION "17.1.0 Lite Edition"
set_global_assignment -name OPTIMIZATION_MODE "HIGH PERFORMANCE EFFORT"
set_global_assignment -name NUM_PARALLEL_PROCESSORS ALL
set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output
set_global_assignment -name SEARCH_PATH "{tree}"
set_global_assignment -name SDC_FILE cf.sdc
set_global_assignment -name SYSTEMVERILOG_FILE "{tree}/v30u_ss_pkg.sv"
set_global_assignment -name SYSTEMVERILOG_FILE "{tree}/v30u_ucrom.sv"
set_global_assignment -name SYSTEMVERILOG_FILE "{tree}/v30u_eu.sv"
set_global_assignment -name VERILOG_MACRO "SYNTHESIS=1"
set_global_assignment -name VERILOG_MACRO "V30_MUXED_AD=1"
{vpins}
"""

SDC = """# WAVE 6 -- the standalone harness's SDC.  NO `set_multicycle_path`: the
# USER RULING of 2026-09-08 makes the NO-EXCEPTION configuration the goal state,
# and the whole point of the measurement is the `ce -> ce` arc under it.
create_clock -name clk -period 31.250 [get_ports clk]
derive_clock_uncertainty
set_false_path -from [get_ports *]
set_false_path -to   [get_ports *]
"""


def qsf(kind):
    tree = os.path.join(SCRATCH, 'tree_' + kind)
    proj = os.path.join(SCRATCH, 'proj_' + kind)
    os.makedirs(proj, exist_ok=True)
    ps = [p for p in ports(tree) if p != 'clk']
    vp = '\n'.join('set_instance_assignment -name VIRTUAL_PIN ON -to %s' % p
                   for p in ps)
    open(os.path.join(proj, 'cf.qsf'), 'w').write(
        QSF.format(tree=tree, vpins=vp))
    open(os.path.join(proj, 'cf.sdc'), 'w').write(SDC)
    # ⚠ `v30u_ucrom`'s `HEXDIR` defaults to "rtl/ucore/" UNDER `SYNTHESIS`,
    # relative to the tool's cwd.  F44 is the standing warning: a wrong HEXDIR
    # gives two $readmemh WARNINGS, an ALL-ZERO ROM and a compile that
    # SUCCEEDS.  The symlink puts the tables where the parameter looks, and the
    # driver's `Q6` check re-reads the map report for the warning.
    link = os.path.join(proj, 'rtl')
    if os.path.islink(link) or os.path.exists(link):
        if os.path.islink(link):
            os.remove(link)
        else:
            shutil.rmtree(link)
    os.makedirs(link)
    os.symlink(tree, os.path.join(link, 'ucore'))
    print('[qsf] %s   %d virtual pins' % (proj, len(ps)))
    return proj


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gen', action='store_true')
    ap.add_argument('--qsf', action='store_true')
    ap.add_argument('--verify', action='store_true')
    ap.add_argument('--clocks', type=int, default=400000)
    ap.add_argument('--out', default=os.path.join(
        ROOT, 'sw/testdata/chainflat/proto.json'))
    a = ap.parse_args()
    meta = {}
    if a.gen:
        meta = gen()
    if a.qsf:
        meta['projects'] = {k: qsf(k) for k in ('ref', 'flat')}
    ok = True
    if a.verify:
        ok, v = verify(clocks=a.clocks)
        meta['verify'] = v
    if meta:
        os.makedirs(os.path.dirname(a.out), exist_ok=True)
        json.dump(meta, open(a.out, 'w'), indent=1, default=str)
        print('wrote %s' % a.out)
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
