#!/usr/bin/env python3
"""WAVE 6 (THE CHAIN FLATTENING STUDY) -- THE PROTOTYPE GENERATOR.

**IT WRITES NOTHING INTO `hdl/`.**  Both trees are generated under
`~/.cache/ucsimt-tmp/chainflat/` and the core never references them.  Deliverable
D's two arms:

  REF   a byte-identical copy of `hdl/rtl/ucore/` -- the 7-copy unrolled chain
        AS IT EXISTS.  It is the POSITIVE CONTROL (bar F-2): synthesised alone
        it must still show WAVE 5's shape.
  FLAT  the same tree with ONE substitution: the bounded `for (chain ...)` loop
        -- SEVEN full copies of a 33-arm `case` -- replaced by

            position 0 : the 33-arm case, once
            then       : the NINE chainable arms, ONCE EACH, in TOPOLOGICAL
                         ORDER, each guarded by `st_n == S_X`

THE ARGUMENT THAT THE SUBSTITUTION IS EXACT, AND IT IS CHECKED BY SIMULATION,
NOT BY THE ARGUMENT.  `sw/chainflat_graph.py` derives that the fall-through
graph is a **DAG** over exactly the nine `st_zero_ok` states, so one edge's walk
visits each state AT MOST ONCE and is a SUBSEQUENCE of any topological order.
The loop and the flat pass therefore compute the same function.  **That is an
argument; the gate is `--verify`**, which runs the flat tree through the whole
169,000-case golden suite and the four LFSR seeds and requires
169,000 / 169,000 plus BYTE-IDENTICAL LFSR signatures against REF.

⚠ **THE FLAT FORM IS NOT A DESIGN PROPOSAL.**  It exists to put a number on the
question "would a flattened composed cone be shorter?".  Nothing here is
proposed for `hdl/rtl/ucore/` and nothing here is landed.

USAGE
  python3 sw/chainflat_proto.py --gen                generate both trees
  python3 sw/chainflat_proto.py --verify             build + score both
  python3 sw/chainflat_proto.py --gen --qsf          + standalone Quartus projects
"""
